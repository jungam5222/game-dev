// 비스듬한 지팡이 (45도). dir 1 = 위가 오른쪽, -1 = 위가 왼쪽, 2 = 아래 오른쪽(앞으로 내림)
function slantStaff(head, len, dir) {
  const n = len + head.h;
  const w = len + head.w + 2;
  const g = Array.from({ length: n + 2 }, () => Array(w).fill("."));
  // 자루: 두 칸 굵기 (위는 밝게)
  for (let i = 0; i < len; i++) {
    const x = dir === -1 ? head.w - 2 + i : w - head.w + 1 - i;
    const y = head.h - 2 + i;
    if (g[y] && g[y][x] !== undefined) g[y][x] = "k";
    if (g[y + 1] && g[y + 1][x] !== undefined) g[y + 1][x] = "b";
  }
  // 머리
  const hx = dir === -1 ? 0 : w - head.w;
  for (let j = 0; j < head.h; j++) for (let i = 0; i < head.w; i++) if (head.rows[j][i] !== ".") g[j][hx + i] = head.rows[j][i];
  let s = { w, h: n + 2, rows: g.map((r) => r.join("")), pal: ALLPAL, _c: null };
  // 잡는 곳: 자루 끝에서 4칸 위
  const k = len - 4;
  s.gx = dir === -1 ? head.w - 2 + k : w - head.w + 1 - k;
  s.gy = head.h - 2 + k;
  if (dir === 2) {
    // 아래로: 위아래 뒤집기
    s = { ...s, rows: [...s.rows].reverse(), gy: s.h - 1 - s.gy };
  }
  return s;
}
