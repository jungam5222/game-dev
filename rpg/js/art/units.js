// 그림의 실제 칠한 범위 (발끝 기준을 잡기 위해)
function bbox(s) {
  let x0 = s.w, y0 = s.h, x1 = -1, y1 = -1;
  for (let j = 0; j < s.h; j++)
    for (let i = 0; i < s.w; i++)
      if (s.rows[j][i] !== ".") {
        if (i < x0) x0 = i;
        if (i > x1) x1 = i;
        if (j < y0) y0 = j;
        if (j > y1) y1 = j;
      }
  return { x0, y0, x1, y1 };
}
export const MONSTER_TOP = {};
export const MONSTER_W = {};
for (const k in MON) {
  const m = MON[k];
  const b = bbox(m.f[0]);
  // 발끝 = 첫 그림의 맨 아래 칠한 줄 바로 밑, 가운데 = 칠한 범위 가운데
  m.ax = Math.round((b.x0 + b.x1 + 1) / 2);
  m.ay = b.y1 + 1;
  MONSTER_TOP[k] = m.ay - b.y0 + (m.fly || 0);
  MONSTER_W[k] = b.x1 - b.x0 + 1;
  m.shw = Math.max(4, Math.round(MONSTER_W[k] * 0.36));
}

// 몬스터 그리기. (x, y) = 발끝 가운데 (박쥐는 그림자 자리)
export function drawMonster(ctx, k, x, y, o = {}) {
  const m = MON[k] || MON.slime;
  const t = o.t || 0;
  x = Math.round(x);
  y = Math.round(y);
  const a = o.alpha == null ? 1 : o.alpha;
  let f;
  let lift = m.fly || 0;
  if (o.dead) {
    f = m.dead;
    lift = 0;
  } else if (o.swing > 0.4) f = m.atk;
  else f = m.f[Math.floor(t / m.sp) % 2];
  if (m.fly && !o.dead) lift += Math.round(Math.sin(t * 3.1) * 1.5);
  shadowAt(ctx, x, y, m.fly && !o.dead ? Math.round(m.shw * 0.7) : m.shw, m.shw > 9 ? 3 : 2, (m.fly && !o.dead ? 0.2 : 0.28) * a);
  blit(ctx, f, x - m.ax, y - m.ay - lift, { flash: o.flash, alpha: a });
}

// ───────── 수호 정령 ─────────
const SPIRIT = [SPIRIT_0, SPIRIT_1, SPIRIT_0, SPIRIT_2];
export const SPIRIT_TOP = 22;
export function drawSpirit(ctx, x, y, o = {}) {
  const t = o.t || 0;
  const a = o.alpha == null ? 1 : o.alpha;
  x = Math.round(x);
  y = Math.round(y);
  const f = SPIRIT[Math.floor(t * 6) % 4];
  const lift = 7 + Math.round(Math.sin(t * 2.6) * 1.5);
  shadowAt(ctx, x, y, 4, 1, 0.18 * a);
  // 발밑에 옅은 빛
  ctx.save();
  ctx.globalAlpha = 0.18 * a;
  ctx.fillStyle = PAL.C;
  ctx.fillRect(x - 3, y - 1, 7, 1);
  ctx.restore();
  blit(ctx, f, x - 6, y - f.h - lift, { flash: o.flash, alpha: a });
}

// ═════════════ 미리보기 ═════════════
// 위: 영웅 (앞·뒤·옆 걸음 4장씩, 왼쪽, 깜박, 전투 서기·치켜듦·내려침·주문·쓰러짐)
// 아래: 몬스터 (숨 2장, 공격, 쓰러짐), 수호 정령. 360×240에 맞춘다.
export function preview(ctx, W_, H_, t) {
  for (let y = 0; y < H_; y += 8)
    for (let x = 0; x < W_; x += 8) {
      ctx.fillStyle = (x / 8 + y / 8) % 2 ? "#3a4466" : "#353e5e";
      ctx.fillRect(x, y, 8, 8);
    }
  let yy = 31;
  for (const cls of ["warrior", "mage", "priest"]) {
    const Hh = heroOf(cls);
    let xx = 9;
    for (const dir of ["down", "up", "right"]) {
      for (let i = 0; i < 4; i++) {
        shadowAt(ctx, xx, yy, 6, 2);
        draw(ctx, Hh.walk[dir].walk[i], xx, yy);
        xx += 15;
      }
      xx += 2;
    }
    drawHero(ctx, cls, xx, yy, { dir: "left", walking: true, t: 0 });
    xx += 15;
    shadowAt(ctx, xx, yy, 6, 2);
    draw(ctx, Hh.walk.down.blink, xx, yy);
    xx += 19;
    for (const k of ["idle", "wind", "strike", "cast"]) {
      const o = { battle: true, t: 0, swing: k === "wind" ? 0.4 : k === "strike" ? 0.8 : 0, cast: k === "cast" ? 1 : 0 };
      drawHero(ctx, cls, xx, yy, o);
      xx += 21;
    }
    drawHero(ctx, cls, xx + 4, yy, { battle: true, down: true });
    yy += 34;
  }
  // 몬스터: [숨1, 숨2, 공격, 쓰러짐]을 실제 칠한 폭대로 붙여 놓는다. "*" = 수호 정령 셋
  const ext = (k, s, dead) => {
    const m = MON[k];
    const b = bbox(s);
    return { l: m.ax - b.x0, r: b.x1 + 1 - m.ax, top: m.ay - b.y0 + (dead ? 0 : m.fly || 0) };
  };
  let cy = yy - 32;
  for (const keys of [["skeleton", "goblin", "bat", "*"], ["golem", "goblin_chief"], ["wolf_king", "spider"], ["wolf", "slime"]]) {
    const items = [];
    for (const k of keys) {
      if (k === "*") {
        for (let i = 0; i < 3; i++) items.push({ spirit: i, l: 6, r: 6, top: SPIRIT_TOP, gap: i === 2 ? 0 : 1 });
        continue;
      }
      const m = MON[k];
      [
        [m.f[0], { t: 0 }],
        [m.f[1], { t: m.sp }],
        [m.atk, { swing: 1 }],
        [m.dead, { dead: true }],
      ].forEach(([s, o], i) => items.push({ k, o, ...ext(k, s, o.dead), gap: i === 3 ? 4 : 1 }));
    }
    const top = Math.max(...items.map((it) => it.top));
    const base = cy + top;
    let xx = 3;
    for (const it of items) {
      xx += it.l;
      if (it.k) drawMonster(ctx, it.k, xx, base, it.o);
      else drawSpirit(ctx, xx, base, { t: it.spirit * 0.17 });
      xx += it.r + it.gap;
    }
    cy = base + 3;
  }
}
