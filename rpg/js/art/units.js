// 걷기·서기 프레임: dir별 [4 걸음] + 서기 [숨2] + 깜박
function buildWalk(cls) {
  const K = KIT[cls];
  const out = {};
  for (const dir of ["down", "up", "right"]) {
    const up0 = K.up[dir];
    const upBl = dir === "right" ? blinkS(up0, K.upY) : dir === "down" ? blinkF(up0, K.upY) : up0;
    const one = (lowS, lowFlip, bob, armKey, blink) => {
      const u = blink ? upBl : up0;
      const y = K.upY + bob;
      const p = [];
      if (cls === "warrior") {
        if (dir === "right") p.push(at(W.shieldS, 13, 15 + bob));
        p.push(at(lowS, 0, K.lowY, lowFlip), at(u, 0, y));
        if (dir === "down") p.push(at(W.swD, 2, 22 + bob), at(W.shield, 11, 15 + bob));
        else if (dir === "up") p.push(at(W.swD, 12, 22 + bob), at(W.shieldB, 0, 15 + bob));
        else {
          const arm = K.arm[armKey];
          p.push(inHand(arm, 9, 16 + bob, W.swD), at(arm, 9, 16 + bob));
        }
      } else {
        if (dir === "down") p.push(at(K.staff, -1, -3 + bob), at(lowS, 0, K.lowY, lowFlip), at(u, 0, y));
        else if (dir === "up") p.push(at(lowS, 0, K.lowY, lowFlip), at(u, 0, y), at(K.staff, 16, -3 + bob));
        else {
          const arm = K.arm.hold;
          p.push(at(lowS, 0, K.lowY, lowFlip), at(u, 0, y), inHand(arm, 9, 16 + bob, K.staff), at(arm, 9, 16 + bob));
        }
      }
      return frame(p);
    };
    const L = dir === "right" ? K.lowS : K.lowF;
    if (dir === "right")
      out[dir] = {
        walk: [one(L[1], false, 0, "back"), one(L[2], false, -1, "down"), one(L[3], false, 0, "fwd"), one(L[2], false, -1, "down")],
        idle: [one(L[0], false, 0, "down"), one(L[0], false, -1, "down")],
        blink: one(L[0], false, 0, "down", true),
      };
    else
      out[dir] = {
        walk: [one(L[1], false, 0), one(L[0], false, -1), one(L[1], true, 0), one(L[0], false, -1)],
        idle: [one(L[0], false, 0), one(L[0], false, -1)],
        blink: one(L[0], false, 0, null, true),
      };
  }
  return out;
}

// 전투 프레임 (오른쪽 보기): idle[2], wind, strike, cast, down
// 팔은 어깨(9, 16)에 맞춰 놓고, 무기를 먼저 그린 뒤 손을 위에 얹는다
function armParts(arm, wp, bob) {
  const x = 9 - arm.sx;
  const y = 16 - arm.sy + bob;
  return [inHand(arm, x, y, wp), at(arm, x, y)];
}
function buildBattle(cls) {
  const K = KIT[cls];
  const u = K.up.right;
  const y0 = K.upY;
  const A = K.barm;
  const out = {};
  const war = cls === "warrior";
  // behind: 팔과 무기를 몸 뒤에 (머리 뒤로 치켜든 자세)
  const base = (bob, arm, wp, extra, behind) => {
    const ap = armParts(arm, wp, bob);
    return frame([war && at(W.shieldS, 14, 15 + bob), ...(behind ? ap : []), at(war ? W.legBt : K.lowBt, 0, K.lowY), at(u, 0, y0 + bob), ...(behind ? [] : ap), ...(extra || [])]);
  };
  if (war) {
    out.idle = [base(0, A.hold, W.swUR), base(-1, A.hold, W.swUR)];
    out.wind = base(0, A.back, W.swUL, null, true);
    out.strike = base(0, A.strike, W.swDR, [at(SMEAR, 12, 6)]);
    out.cast = base(0, A.strike, W.swU);
  } else {
    out.idle = [base(0, A.hold, K.staff), base(-1, A.hold, K.staff)];
    out.wind = base(0, A.back, K.sUL, null, true);
    out.strike = base(0, A.strike, K.sDR, [at(SMEAR, 13, 6)]);
    out.cast = base(0, A.strike, K.staff);
    // 빛 자리: 지팡이 머리 가운데 (발끝 기준)
    const ar = A.strike;
    const s = K.staff;
    const wx = 9 - ar.sx + ar.hx - s.gx;
    const wy = 16 - ar.sy + ar.hy - s.gy;
    out.cast.glow = [wx + Math.floor(K.head.w / 2) - 10 + (cls === "priest" ? 0 : 0), wy + Math.floor(K.head.h / 2) - 28];
  }
  // 쓰러짐: 옆 모습(무기 없이)을 눕힌다
  const lying = comp(FW, FH, AX, AY, [at(K.lowS[0], 0, K.lowY), at(blinkS(u, y0), 0, y0)]);
  const r = rotL(lying);
  out.down = { ...r, ax: AY - 6, ay: r.h - (FW - AX - 6) };
  return out;
}

