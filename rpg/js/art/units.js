const ALLPAL = { ...PAL, ...GLOW };

// 여러 조각을 한 장으로 겹치기. parts: [그림, x, y, 뒤집기] (뒤 조각이 위). (ax, ay) = 발끝
function comp(w, h, ax, ay, parts) {
  const g = Array.from({ length: h }, () => Array(w).fill("."));
  for (const p of parts) {
    if (!p) continue;
    const [s, x0, y0, flip] = p;
    for (let j = 0; j < s.h; j++)
      for (let i = 0; i < s.w; i++) {
        const ch = s.rows[j][flip ? s.w - 1 - i : i];
        if (ch === "." || ch === " ") continue;
        const x = x0 + i;
        const y = y0 + j;
        if (x >= 0 && y >= 0 && x < w && y < h) g[y][x] = ch;
      }
  }
  return { w, h, rows: g.map((r) => r.join("")), pal: ALLPAL, _c: null, ax, ay };
}
// 몇 칸만 바꾼 새 그림. list: [x, y, 글자]
function put(s, list) {
  const g = s.rows.map((r) => [...r]);
  for (const [x, y, ch] of list) if (g[y] && x >= 0 && x < s.w) g[y][x] = ch;
  return { ...s, rows: g.map((r) => r.join("")), _c: null };
}
// 글자 바꾸기 (새 그림)
function swap(s, map) {
  return { ...s, rows: s.rows.map((r) => [...r].map((c) => map[c] || c).join("")), _c: null };
}
// 90도 돌리기 (반시계: 위쪽이 왼쪽으로)
function rotL(s) {
  const rows = [];
  for (let i = s.w - 1; i >= 0; i--) {
    let r = "";
    for (let j = 0; j < s.h; j++) r += s.rows[j][i];
    rows.push(r);
  }
  return { w: s.h, h: s.w, rows, pal: s.pal, _c: null };
}
// 발끝 기준으로 찍기
function draw(ctx, f, x, y, o = {}) {
  blit(ctx, f, x - f.ax, y - f.ay, o);
}

