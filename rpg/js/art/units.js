// 영웅 그리기. (x, y) = 발끝 가운데
export function drawHero(ctx, cls, x, y, o = {}) {
  const H = heroOf(KIT[cls] ? cls : "warrior");
  const t = o.t || 0;
  const bo = { flash: o.flash, alpha: o.alpha };
  x = Math.round(x);
  y = Math.round(y);
  if (o.down) {
    shadowAt(ctx, x, y, 10, 2, 0.25 * (o.alpha == null ? 1 : o.alpha));
    draw(ctx, H.battle.down, x, y, bo);
    return;
  }
  shadowAt(ctx, x, y, 6, 2, 0.28 * (o.alpha == null ? 1 : o.alpha));
  if (o.battle) {
    const B = H.battle;
    let f;
    if (o.cast > 0) f = B.cast;
    else if (o.swing > 0.55) f = B.strike;
    else if (o.swing > 0.2) f = B.wind;
    else f = B.idle[Math.floor(t / 0.6) % 2];
    draw(ctx, f, x, y, bo);
    if (o.cast > 0 && cls !== "warrior") castGlow(ctx, cls, f, x, y, o.cast, t);
    return;
  }
  const dir = o.dir || "down";
  const D = H.walk[dir === "left" ? "right" : dir];
  let f;
  if (o.walking) f = D.walk[Math.floor(t * 8) % 4];
  else {
    const blink = t % 3.7 < 0.13;
    f = blink ? D.blink : D.idle[Math.floor(t / 0.6) % 2];
  }
  if (dir === "left") blit(ctx, f, x - (f.w - f.ax), y - f.ay, { ...bo, flip: true });
  else draw(ctx, f, x, y, bo);
}

// 주문 빛: 지팡이 머리 둘레에 번지는 빛 (cast가 클수록 크게)
function castGlow(ctx, cls, f, x, y, c, t) {
  if (!f.glow) return;
  const cx = x + f.glow[0];
  const cy = y + f.glow[1];
  const r = 3 + Math.round(c * 4) + (Math.floor(t * 10) % 2);
  ctx.save();
  ctx.fillStyle = cls === "mage" ? PAL.C : PAL.y;
  for (const [rr, a] of [[r, 0.22 + 0.18 * c], [Math.max(1, r - 3), 0.35 + 0.25 * c]]) {
    ctx.globalAlpha = a;
    for (let j = -rr; j <= rr; j++) {
      const w = Math.round(Math.sqrt(rr * rr - j * j));
      ctx.fillRect(cx - w, cy + j, w * 2 + 1, 1);
    }
  }
  ctx.restore();
}

