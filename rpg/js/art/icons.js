// 외곽선 없이 칠한 모양을 적으면 바깥에 1픽셀 외곽선을 자동으로 두른다(상하좌우 이웃).
// 외곽선 색은 재질 따라: 따뜻한 색 → d, 쇠·돌 → K, 파랑 → n, 초록 → D
const OLC = {};
for (const ch of "dbktcoRmrPhOgy12pM") OLC[ch] = "d";
for (const ch of "KnlSesW") OLC[ch] = "K";
for (const ch of "uBC") OLC[ch] = "n";
for (const ch of "DFGL") OLC[ch] = "D";
// 외곽선을 두르지 않는 픽셀 (반짝임, 떠 있는 점, 바람 줄)
const BARE = { "*": "W", "+": "y", "~": "C", "=": "s", "^": "g", "%": "M", "!": "B", "?": "O", ";": "P", ":": "c", "-": "e", "_": "L", "&": "r", "#": "S", "@": "t", "<": "k", ">": "b" };

function lines(text) {
  const ls = text.split("\n").map((l) => l.trim());
  while (ls.length && !ls[0]) ls.shift();
  while (ls.length && !ls[ls.length - 1]) ls.pop();
  return ls;
}
// 문자열 → 격자(글자 배열). size보다 작으면 가운데에 놓는다.
function cells(text, size) {
  const ls = lines(text);
  const w = Math.max(...ls.map((l) => l.length));
  if (ls.some((l) => l.length !== w)) console.warn("줄 길이가 다름:\n" + text);
  const W = size || w;
  const H = size || ls.length;
  if (w > W || ls.length > H) throw new Error(`아이콘이 ${W}×${H}보다 큼: ${w}×${ls.length}\n${text}`);
  const ox = (W - w) >> 1;
  const oy = (H - ls.length) >> 1;
  const g = [];
  for (let y = 0; y < H; y++) {
    const row = [];
    for (let x = 0; x < W; x++) {
      const l = ls[y - oy];
      const ch = l && x - ox >= 0 ? l[x - ox] : undefined;
      row.push(ch && ch !== " " ? ch : ".");
    }
    g.push(row);
  }
  return g;
}
function outline(g, force) {
  const H = g.length;
  const W = g[0].length;
  const out = g.map((r) => r.slice());
  for (let y = 0; y < H; y++)
    for (let x = 0; x < W; x++) {
      if (g[y][x] !== ".") continue;
      const cnt = {};
      for (const [dx, dy] of [[0, 1], [1, 0], [0, -1], [-1, 0]]) {
        const ch = g[y + dy] && g[y + dy][x + dx];
        if (!ch || ch === "." || ch in BARE || !(ch in OLC)) continue;
        const o = force || OLC[ch];
        cnt[o] = (cnt[o] || 0) + 1;
      }
      let best = null;
      for (const k in cnt) if (!best || cnt[k] > cnt[best] || (cnt[k] === cnt[best] && k === "K")) best = k;
      if (best) out[y][x] = best;
    }
  return out;
}
const gridText = (g) => g.map((r) => r.join("")).join("\n");
const toSpr = (g, map) => spr(g.map((r) => r.map((ch) => BARE[ch] || ch).join("")).join("\n"), map);

// 아이콘 하나: 칠한 모양 → 외곽선 → 그림 조각. o.o = 외곽선 색 고정, o.raw = 외곽선 없음, o.size = 크기(기본 16)
function ic(text, o = {}) {
  let g = typeof text === "string" ? cells(text, o.size == null ? 16 : o.size) : text.map((r) => r.slice());
  if (!o.raw) g = outline(g, o.o);
  return toSpr(g, o.map);
}
// 그림 조각 겹치기: 위 그림의 투명이 아닌 픽셀이 아래를 덮는다
function over(base, top, dx = 0, dy = 0) {
  const rows = base.rows.map((r) => [...r]);
  for (let y = 0; y < top.h; y++)
    for (let x = 0; x < top.w; x++) {
      const ch = top.rows[y][x];
      if (ch === "." || ch === " ") continue;
      const Y = y + dy;
      const X = x + dx;
      if (Y < 0 || X < 0 || Y >= base.h || X >= base.w) continue;
      rows[Y][X] = ch;
    }
  return spr(rows.map((r) => r.join("")).join("\n"), { ...base.pal, ...top.pal });
}
// 색 바꾼 새 그림 (외곽선 포함 그대로)
function swap(s, m) {
  return spr(s.rows.map((r) => [...r].map((ch) => m[ch] || ch).join("")).join("\n"), s.pal);
}
const flipH = (s) => spr(s.rows.map((r) => [...r].reverse().join("")).join("\n"), s.pal);

// 계산으로 칠하기 (고리, 소용돌이처럼 손으로 적기 힘든 모양). f(x, y) → 글자 또는 null (픽셀 가운데 좌표)
function grid(n = 16) {
  return Array.from({ length: n }, () => Array(n).fill("."));
}
function paint(g, f) {
  for (let y = 0; y < g.length; y++)
    for (let x = 0; x < g[0].length; x++) {
      const ch = f(x + 0.5, y + 0.5, g[y][x]);
      if (ch) g[y][x] = ch;
    }
  return g;
}
// 격자 위에 문자열 그림 얹기 ('.'은 건너뜀)
function stamp(g, text, x0 = 0, y0 = 0) {
  lines(text).forEach((l, j) => [...l].forEach((ch, i) => ch !== "." && g[y0 + j] && (g[y0 + j][x0 + i] = ch)));
  return g;
}
// 왼쪽 위 빛 기준 명암 (-1 어두움 ~ 1 밝음): 바깥 방향 벡터 (dx, dy)
const lit = (dx, dy) => -(dx + dy) / (Math.hypot(dx, dy) * Math.SQRT2 || 1);
// 고리(띠) 칠하기: 반지름 r0~r1, 각도 a0~a1(도, 0=오른쪽, 시계 방향), 색 [밝음, 중간, 어두움]
function ring(g, cx, cy, r0, r1, cols, a0 = -180, a1 = 180) {
  return paint(g, (x, y) => {
    const dx = x - cx;
    const dy = y - cy;
    const d = Math.hypot(dx, dy);
    if (d < r0 || d >= r1) return null;
    let a = (Math.atan2(dy, dx) * 180) / Math.PI;
    if (a < a0) a += 360;
    if (a < a0 || a > a1) return null;
    const l = lit(dx, dy) * (d > (r0 + r1) / 2 ? 1 : -1);
    return l > 0.35 ? cols[0] : l < -0.35 ? cols[2] : cols[1];
  });
}

