export function drawNine(ctx, f, x, y, w, h) {
  const img = canvasOf(f.s);
  const n = f.slice;
  const sw = f.s.w;
  const sh = f.s.h;
  x = Math.round(x);
  y = Math.round(y);
  w = Math.round(w);
  h = Math.round(h);
  const cw = sw - 2 * n;
  const ch = sh - 2 * n;
  const xs = [[0, n, x, n], [n, cw, x + n, w - 2 * n], [sw - n, n, x + w - n, n]];
  const ys = [[0, n, y, n], [n, ch, y + n, h - 2 * n], [sh - n, n, y + h - n, n]];
  ctx.save();
  ctx.imageSmoothingEnabled = false;
  for (const [sx, sW, dx, dW] of xs) for (const [sy, sH, dy, dH] of ys) if (dW > 0 && dH > 0) ctx.drawImage(img, sx, sy, sW, sH, dx, dy, dW, dH);
  ctx.restore();
}

