function frame(W, H, P, fill, o = {}) {
  const g = grid(Math.max(W, H)).slice(0, H).map((r) => r.slice(0, W));
  for (let y = 0; y < H; y++)
    for (let x = 0; x < W; x++) {
      const ds = [[y, P.top], [x, P.left], [H - 1 - y, P.bottom], [W - 1 - x, P.right]];
      let best = null;
      for (const [d, p] of ds) if (d < p.length && (!best || d < best[0])) best = [d, p];
      g[y][x] = best ? best[1][best[0]] : fill;
    }
  // 둥근 모서리
  const r = o.round == null ? 1 : o.round;
  if (r) {
    const oc = P.top[0];
    for (const [cx, cy, sx, sy] of [[0, 0, 1, 1], [W - 1, 0, -1, 1], [0, H - 1, 1, -1], [W - 1, H - 1, -1, -1]]) {
      g[cy][cx] = ".";
      if (r > 1) {
        g[cy][cx + sx] = ".";
        g[cy + sy][cx] = ".";
        g[cy + sy][cx + sx] = oc;
      }
    }
  }
  return g;
}
