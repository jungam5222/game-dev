export function preview(ctx, W, H) {
  const zq = typeof location !== "undefined" && new URLSearchParams(location.search).get("zoom");
  if (zq) return zoomView(ctx, W, H, zq);
  // 위: 아이콘 전부(카드 → 기술 → 의도 → 재료 → 메뉴 순서)를 크림 띠와 짙은 나무 띠에 한 번씩
  const all = [...Object.values(C), ...Object.values(SK), ...Object.values(MV), ...Object.values(MAT), ...Object.values(UI)];
  const per = Math.max(1, Math.floor((W - 2) / 17));
  const rows = Math.ceil(all.length / per);
  const sh = rows * 17 + 3;
  [["#ead4aa", 0], ["#733e39", sh]].forEach(([bg, y0]) => {
    ctx.fillStyle = bg;
    ctx.fillRect(0, y0, W, sh);
    all.forEach((s, i) => blit(ctx, s, 2 + (i % per) * 17 + ((16 - s.w) >> 1), y0 + 2 + Math.floor(i / per) * 17 + ((16 - s.h) >> 1)));
  });
  // 아래: 틀마다 작게(28×20)·크게(56×34) 늘려 그리기, 마지막 칸에 방향 단추·보석
  let y = sh * 2;
  ctx.fillStyle = "#3e8948";
  ctx.fillRect(0, y, W, H - y);
  y += 2;
  const fs = Object.values(FRAMES);
  const cw = 88;
  const cols = Math.max(1, Math.floor((W - 2) / cw));
  fs.forEach((f, i) => {
    const x = 2 + (i % cols) * cw;
    const yy = y + Math.floor(i / cols) * 36;
    drawNine(ctx, f, x, yy + 7, 28, 20);
    drawNine(ctx, f, x + 30, yy, 56, 34);
  });
  const k = fs.length;
  let x = 2 + (k % cols) * cw;
  const yy = y + Math.floor(k / cols) * 36;
  [ARROWS.up, ARROWS.down, ARROWS.left, ARROWS.right].forEach((s, i) => blit(ctx, s, x + (i % 2) * 17, yy + Math.floor(i / 2) * 17));
  blit(ctx, MANA_GEM, x + 36, yy + 2);
  CARD_GEMS.forEach((s, i) => blit(ctx, s, x + 48 + (i % 2) * 10, yy + 2 + Math.floor(i / 2) * 9));
}

